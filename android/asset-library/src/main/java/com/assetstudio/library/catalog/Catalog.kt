package com.assetstudio.library.catalog

import com.assetstudio.library.BuildConfig
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/**
 * Wire format of the static catalog published by GitHub Pages.
 *
 * The app has no API server: everything it renders comes from files under
 * `<pages-base>/catalog/…` and `<pages-base>/assets/…`. The documents here mirror
 * `scripts/build_pages_site.py`, which is the only producer of that tree.
 */
@Serializable
data class CatalogIndex(
    @SerialName("schema_version") val schemaVersion: String = "",
    val kind: String = "",
    @SerialName("generated_at") val generatedAt: String = "",
    @SerialName("base_url") val baseUrl: String = "",
    val counts: CatalogCounts = CatalogCounts(),
    val models: List<CatalogAsset> = emptyList(),
    val animations: List<CatalogAsset> = emptyList(),
    val skipped: List<CatalogSkipped> = emptyList()
) {
    val total: Int get() = models.size + animations.size
}

@Serializable
data class CatalogCounts(val models: Int = 0, val animations: Int = 0)

/** A glTF sidecar: the `.bin` buffer or one of the textures the `.gltf` points at. */
@Serializable
data class CatalogDependency(
    val role: String = "",
    val path: String = "",
    val url: String = "",
    val bytes: Long = 0,
    val sha256: String = ""
)

@Serializable
data class CatalogSkipped(
    val id: String = "", val kind: String = "", val reason: String = ""
)

@Serializable
data class CatalogAsset(
    val id: String = "",
    val kind: String = "",
    val name: String = "",
    val category: String = "",
    @SerialName("source_format") val sourceFormat: String = "",
    val format: String = "GLB",
    val bytes: Long = 0,
    val sha256: String = "",
    @SerialName("validation_status") val validationStatus: String = "",
    val humanoid: Boolean = false,
    @SerialName("target_character_id") val targetCharacterId: String = "",
    @SerialName("retarget_status") val retargetStatus: String = "",
    @SerialName("clip_count") val clipCount: Int = 0,
    @SerialName("duration_seconds") val durationSeconds: Double = 0.0,
    @SerialName("updated_at") val updatedAt: String = "",
    @SerialName("download_url") val downloadUrl: String = "",
    @SerialName("manifest_url") val manifestUrl: String = "",
    @SerialName("gltf_url") val gltfUrl: String? = null,
    val dependencies: List<CatalogDependency> = emptyList()
) {
    val hasGltfBundle: Boolean get() = !gltfUrl.isNullOrBlank()
}

/** Result of one metadata refresh against the Pages catalog. */
data class CatalogRefresh(
    val counts: CatalogCounts,
    val generatedAt: String,
    val baseUrl: String,
    val fromCache: Boolean,
    val skipped: Int = 0
)

/**
 * Catalog state shown on the library screen. Named `HealthDto` because the UI reads
 * `health.assets`, but it is derived from the static catalog: there is no server to
 * report a health endpoint.
 */
data class HealthDto(
    val status: String,
    val version: String,
    val authentication: String,
    val storageDriver: String,
    val validator: String = "",
    val assets: Map<String, Int> = emptyMap()
)

object CatalogDefaults {
    /**
     * The repository's GitHub Pages project site, injected at build time from
     * `android/gradle.properties` (`assetStudio.pagesBaseUrl`). It is derived from
     * the repository slug — `https://<owner>.github.io/<repo>` — never a placeholder
     * host, and the Pages workflow fails if the deployed `base_url` differs.
     */
    val DEFAULT_BASE_URL: String = BuildConfig.CATALOG_BASE_URL

    /** True when [url] is an absolute https URL that is not a placeholder host. */
    fun isUsableBaseUrl(url: String): Boolean {
        val trimmed = url.trim()
        if (!trimmed.startsWith("https://")) return false
        val lowered = trimmed.lowercase()
        return PLACEHOLDERS.none { lowered.contains(it) }
    }

    val PLACEHOLDERS = listOf("example.invalid", "example.com", "localhost", "127.0.0.1")

    fun normaliseBaseUrl(url: String): String = url.trim().trimEnd('/')
}

/** Shared JSON settings: the catalog is generated by Python and must stay lenient. */
val CatalogJson: Json = Json {
    ignoreUnknownKeys = true
    coerceInputValues = true
    isLenient = true
    explicitNulls = false
}
